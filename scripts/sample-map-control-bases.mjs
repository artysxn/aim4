#!/usr/bin/env node
// ---------------------------------------------------------------------------
// Sample soft+active map possession at round clock 01:46 across the shared
// replay library, then rewrite src/replays/coach/mapControlBases.js.
//
// Usage:
//   AIM4_REPLAY_DIR=/path/to/replays node scripts/sample-map-control-bases.mjs
//   node scripts/sample-map-control-bases.mjs --dry-run
// ---------------------------------------------------------------------------

import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { SHARED_LIBRARY } from '../server/replays/auth.js';
import {
  listRoundNames,
  readRoundMeta,
  readRoundTicks
} from '../server/replays/demoStore.js';
import { getZones } from '../server/zonesStore.js';
import { TickTrack } from '../src/replays/tickStore.js';
import {
  buildZonePresence,
  hasControlField,
  prepareControlField,
  registerRadarMask
} from '../src/replays/zones/zoneOverlay.js';
import { loadRadarMask } from './lib/radarMask.mjs';
import {
  possessionSharesAt,
  tickAtMapControlBaseline,
  mapControlAdvantageEnabled
} from '../src/replays/coach/mapControlAdvantage.js';
import { parseRoundId } from '../src/replays/shared/roundId.js';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const OUT = path.join(__dirname, '../src/replays/coach/mapControlBases.js');
const dryRun = process.argv.includes('--dry-run');

async function main() {
  const user = SHARED_LIBRARY;
  const names = await listRoundNames(user);
  console.log(`Library=${user}  rounds=${names.length}`);
  if (!names.length) {
    console.error('No rounds found. Set AIM4_REPLAY_DIR to the replay volume root.');
    process.exitCode = 1;
    return;
  }

  /** @type {Map<string, { ct: number, t: number, n: number }>} */
  const acc = new Map();
  const zoneCache = new Map();
  let skipped = 0;

  for (const file of names) {
    const parsed = parseRoundId(file);
    const map = parsed?.map || String(file).slice(0, 3).toUpperCase();
    if (!map) {
      skipped++;
      continue;
    }

    let network = zoneCache.get(map);
    if (network === undefined) {
      network = await getZones(map);
      // Slim network is enough — the lattice attaches at sample time.
      if (!network) network = { map, visionBlocks: [], elevated: [], bombSites: { a: null, b: null } };
      // No canvas here, so hand the walkable raster in from the PNG directly.
      const mask = await loadRadarMask(map);
      if (mask) registerRadarMask(map, mask);
      else console.warn(`  ${map}: no radar PNG, possession unavailable`);
      zoneCache.set(map, network);
    }
    if (!mapControlAdvantageEnabled(map)) {
      skipped++;
      continue;
    }

    const meta = await readRoundMeta(user, file);
    if (!meta?.players?.length) {
      skipped++;
      continue;
    }
    meta.map = meta.map || map;

    const tick = tickAtMapControlBaseline(meta);
    if (tick == null) {
      skipped++;
      continue;
    }

    const buf = await readRoundTicks(user, file, 1);
    if (!buf) {
      skipped++;
      continue;
    }
    const track = new TickTrack(buf);
    prepareControlField(network, map, null);
    if (!hasControlField(network)) {
      skipped++;
      continue;
    }
    const presence = buildZonePresence({ meta, track, network, mapCode: map });
    if (!presence) {
      skipped++;
      continue;
    }
    const scratch = [];
    track.sampleAll(tick, scratch);
    const shares = possessionSharesAt({
      meta,
      states: scratch,
      network,
      presence,
      tick
    });
    if (!shares) {
      skipped++;
      continue;
    }

    const row = acc.get(map) || { ct: 0, t: 0, n: 0 };
    row.ct += shares.ct;
    row.t += shares.t;
    row.n += 1;
    acc.set(map, row);
    if (row.n % 25 === 0) {
      console.log(`  ${map}: ${row.n} samples…`);
    }
  }

  /** @type {Record<string, { ct: number, t: number, samples: number }>} */
  const bases = {};
  for (const [map, row] of [...acc.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
    if (row.n < 1) continue;
    bases[map] = {
      ct: Math.round((row.ct / row.n) * 100) / 100,
      t: Math.round((row.t / row.n) * 100) / 100,
      samples: row.n
    };
    const relCt = 50 + (bases[map].ct - bases[map].t) / 2;
    console.log(
      `${map}: CT ${bases[map].ct}%  T ${bases[map].t}%  (n=${row.n})  relCT=${relCt.toFixed(1)}`
    );
  }

  console.log(`Skipped ${skipped} rounds (no baseline map / no ticks / planted early).`);

  if (!Object.keys(bases).length) {
    console.error('No baselines computed.');
    process.exitCode = 1;
    return;
  }

  const body = `// ---------------------------------------------------------------------------
// Per-map starting map-control baselines (area % at round clock 01:46).
// Generated by: node scripts/sample-map-control-bases.mjs
// Values are raw CT/T area shares (neutral ignored for the relative bias).
// ---------------------------------------------------------------------------

/**
 * @typedef {{ ct: number, t: number, samples: number }} MapControlBase
 */

/**
 * Average soft+active possession at 01:46 across sampled rounds.
 * Missing maps → map-control win term stays off until sampled.
 *
 * @type {Record<string, MapControlBase>}
 */
export const MAP_CONTROL_BASE = ${JSON.stringify(bases, null, 2)};
`;

  if (dryRun) {
    console.log('\n--dry-run; not writing file.\n');
    console.log(body);
    return;
  }

  await fs.writeFile(OUT, body, 'utf8');
  console.log(`Wrote ${OUT}`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
